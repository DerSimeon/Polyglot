package lol.simeon.polyglot.jda

/** Strips a matching prefix from raw message content and tokenizes the remainder. */
public object MessageCommandParser {
    private val whitespace = Regex("\\s+")

    /** Returns the command tokens if [content] starts with one of [prefixes], else `null`. */
    public fun parse(content: String, prefixes: List<String>): List<String>? {
        val matched = prefixes.filter { it.isNotEmpty() }
            .sortedByDescending { it.length }
            .firstOrNull { content.startsWith(it) }
            ?: return null
        val body = content.removePrefix(matched).trim()
        if (body.isEmpty()) return null
        return body.split(whitespace)
    }
}
